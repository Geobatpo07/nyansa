#!/usr/bin/env bash
# Tests scripts/check-secrets.sh on a throwaway Git repository:
#   - the project's .env.example (with its Tailscale placeholder) is accepted;
#   - a Tailscale auth key in the real format (tskey-auth-<random>) is refused.
# The repository under test is created in a temporary folder; the script
# checks that it runs there before any Git write, and never touches the
# project repository or its configuration.
#
# Usage: scripts/tests/check-secrets.test.sh
set -Eeuo pipefail

# shellcheck source=scripts/lib.sh
source "$(dirname "${BASH_SOURCE[0]}")/../lib.sh"

require_cmd git
root=$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)
scanner=$root/scripts/check-secrets.sh

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
cd "$work"
git init -q .
# Windows path when available (pwd -W), as printed by Git for Windows.
here=$(pwd -W 2>/dev/null || pwd)
[[ "$(git rev-parse --show-toplevel)" == "$here" ]] || die "not inside the throwaway repository: $work"
[[ "$here" != "$(cd "$root" && (pwd -W 2>/dev/null || pwd))" ]] || die "refusing to run in the project repository"

# Identity passed per command: nothing is written to any Git config.
commit() { git -c user.name=test -c user.email=test@example.invalid -c core.autocrlf=false commit -q --no-verify -m "$1"; }

random() { LC_ALL=C tr -dc 'A-Za-z0-9' </dev/urandom | head -c "$1" || true; }

failures=0
check() {
	local label=$1 expected=$2 reason=${3:-} status=0 output
	output=$(bash "$scanner" HEAD 2>&1) || status=$?
	if [[ "$expected" == pass && $status -eq 0 ]] || [[ "$expected" == fail && $status -ne 0 && "$output" == *"$reason"* ]]; then
		echo "ok   $label"
	else
		echo "FAIL $label (exit $status)" >&2
		indent <<<"$output" >&2
		failures=$((failures + 1))
	fi
}

grep -qx 'TS_AUTHKEY=change_me_tailscale_auth_key' "$root/.env.example" \
	|| die ".env.example does not use the expected Tailscale placeholder"
cp "$root/.env.example" .env.example
git -c core.autocrlf=false add .env.example
commit "placeholder"
check "the .env.example placeholders are accepted" pass

# Same shape as a key generated by the Tailscale admin console.
echo "TS_AUTHKEY=tskey-auth-k$(random 10)CNTRL-$(random 32)" >config.txt
git -c core.autocrlf=false add config.txt
commit "real key"
check "a tskey-auth-<random> key is refused" fail "config.txt:1:TS_AUTHKEY=tskey-auth-"

((failures == 0)) || die "$failures check-secrets test(s) failed"
log "check-secrets tests passed"
